WITH agrupacion_costos AS (
    SELECT
        u.DISTRITO,
        f.ANIO,
        f.MES,
        SUM(c.COSTO_SOCIAL_USD) AS COSTO_SOCIAL_MENSUAL,
        SUM(c.CANTIDAD_ACCIDENTE) AS TOTAL_ACCIDENTES,
        AVG(f.PRECIPITACION_MM) AS CLIMA_LLUVIA_PROMEDIO,
        AVG(f.NIEVE_MM) AS CLIMA_NIEVE_PROMEDIO
    FROM NYC_DOT_DW.GOLD_MARTS.FACT_COLISION c
    JOIN NYC_DOT_DW.GOLD_MARTS.DIM_FECHA f
      ON c.FECHA_KEY = f.FECHA_KEY
    JOIN NYC_DOT_DW.GOLD_MARTS.DIM_UBICACION u
      ON c.UBICACION_KEY = u.UBICACION_KEY
    WHERE u.DISTRITO IS NOT NULL
      AND u.DISTRITO <> 'SIN_DATO'
      AND f.ANIO >= 2020
      AND (f.ANIO < 2026 OR (f.ANIO = 2026 AND f.MES <= 6))
    GROUP BY u.DISTRITO, f.ANIO, f.MES
),
agrupacion_quejas AS (
    SELECT
        q.DISTRITO,
        f.ANIO,
        f.MES,
        SUM(IFF(q.TIPO_QUEJA = 'Traffic Signal Condition', 1, 0)) AS QUEJAS_SEMAFOROS,
        SUM(IFF(q.TIPO_QUEJA = 'Street Light Condition', 1, 0)) AS QUEJAS_LUMINARIAS
    FROM NYC_DOT_DW.GOLD_MARTS.FACT_QUEJAS_INFRAESTRUCTURA q
    JOIN NYC_DOT_DW.GOLD_MARTS.DIM_FECHA f
      ON q.FECHA_KEY = f.FECHA_KEY
    WHERE q.DISTRITO IS NOT NULL
      AND q.DISTRITO <> 'Unspecified'
      AND f.ANIO >= 2020
      AND (f.ANIO < 2026 OR (f.ANIO = 2026 AND f.MES <= 6))
    GROUP BY q.DISTRITO, f.ANIO, f.MES
),
agrupacion_ambulancias_global AS (
    SELECT
        f.ANIO,
        f.MES,
        COUNT(*) AS TOTAL_ATENCIONES_CIUDAD
    FROM NYC_DOT_DW.GOLD_MARTS.FACT_ATENCION_MEDICA a
    JOIN NYC_DOT_DW.GOLD_MARTS.DIM_FECHA f
      ON a.FECHA_KEY = f.FECHA_KEY
    WHERE f.ANIO >= 2020
      AND (f.ANIO < 2026 OR (f.ANIO = 2026 AND f.MES <= 6))
    GROUP BY f.ANIO, f.MES
)
SELECT
    c.DISTRITO,
    c.ANIO,
    c.MES,
    c.COSTO_SOCIAL_MENSUAL,
    c.TOTAL_ACCIDENTES,
    COALESCE(q.QUEJAS_SEMAFOROS, 0) AS QUEJAS_SEMAFOROS,
    COALESCE(q.QUEJAS_LUMINARIAS, 0) AS QUEJAS_LUMINARIAS,
    c.CLIMA_LLUVIA_PROMEDIO,
    c.CLIMA_NIEVE_PROMEDIO,
    COALESCE(amb.TOTAL_ATENCIONES_CIUDAD, 0) AS TOTAL_ATENCIONES_CIUDAD
FROM agrupacion_costos c
LEFT JOIN agrupacion_quejas q
  ON c.DISTRITO = q.DISTRITO
 AND c.ANIO = q.ANIO
 AND c.MES = q.MES
LEFT JOIN agrupacion_ambulancias_global amb
  ON c.ANIO = amb.ANIO
 AND c.MES = amb.MES
ORDER BY c.ANIO DESC, c.MES DESC, c.DISTRITO
;

